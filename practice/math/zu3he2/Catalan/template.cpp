/**
 * @brief Catalan数
 * @note
 *   1. 表达式
 *     a. C[n]=C(2n,n)/(n+1)
 *     b. C[n]=(2n)!/(n!(n+1)!)
 *     c. C[n]=C(2n,n)-C(2n,n+1)
 *     d. C[n]=C[n-1] (4n-2)/(n+1),C[0]=C[1]=1
 *     e. C[n]=sum^(n-1)_0{C[i]C[n-1-i]}
 *   2. 表征意义
 *     a. 给定正负一序列{a[i]},前缀和S[i]:=sum(a,1,i)
 *        需保证任意i,S[i]>=0
 *        超额量T:=S[i]<0且a[i]=-1的数量
 *        可以证明，T属于[0,n]，且每种情况的数列数量都相同
 *     c. 从(0,0)走到(n,n)，只能向右或向上，不允许在y=x直线上方
 *        可通过y=x+1直线对称过去，每一种非法情况都对应(0,0)走到(n-1,n+1)的路径
 *        总=C(2n,n)，非法=C(2n,n+1)
 *     de. n+2边形的三角剖分方案数
 *     de. 含有n个节点的形态不同的二叉树数目
 */
